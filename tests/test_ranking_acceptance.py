def test_reading_the_vendors_enterprise_value_again_would_change_this_answer(monkeypatch):
    """The regression rule 8 exists to stop, executed. Divide by the vendor's
    field instead of the parts and LISP.SW is back on 27.4% -- the
    impossible figure L2 caught, yield rank 1, place 32 under E43 -- and the
    fifth name changes (NHY.OL for AUTO.L), on an enterprise value struck at
    a price of the vendor's choosing."""
    from vss import ranking

    def vendor(inputs, rate):
        if inputs.enterprise_value_quoted is None or rate is None:
            return ranking.EvParts(None, None, None, "no enterprise value")
        return ranking.EvParts(None, None, rate.convert(inputs.enterprise_value_quoted), None)

    monkeypatch.setattr(ranking, "enterprise_value_parts", vendor)
    monkeypatch.setattr(ranking, "implied_net_cash_note", lambda inputs, rate=None: None)
    candidates, records, table = load()
    wrong = rank_frozen(candidates, records, table)
    assert [r.ticker for r in wrong.main[:5]] != [row[1] for row in TOP_FIVE]
    assert wrong.main[4].ticker == "NHY.OL"
    lisp = next(r for r in wrong.main if r.ticker == "LISP.SW")
    assert lisp.ey_rank == 1
    assert lisp.scored.earnings_yield == pytest.approx(0.2743, abs=5e-4)


