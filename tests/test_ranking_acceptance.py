def test_the_unit_check_does_not_move_with_its_tolerance():
    """If the answer depended on the tolerance, the tolerance would be a
    threshold. It does not: the same one name at 1e-9 and at 1e-2."""
    from vss import ranking

    _, records, _ = load()
    for tolerance in (1e-9, 1e-6, 1e-3, 1e-2):
        hits = sorted(
            ticker for ticker, record in records.items()
            if any(ranking.is_unit_slip(a, b, tolerance=tolerance)
                   for a, b in _alias_pairs(record))
        )
        assert hits == ["MONC.MI"], f"tolerance {tolerance} gives {hits}"


def _alias_pairs(record):
    """Every ordered pair of alias values sharing one year end."""
    from vss.ranking import EBIT_ALIASES

    found = {}
    for alias in EBIT_ALIASES:
        hit = record.latest(alias)
        if hit is not None:
            found[alias] = hit
    for first, (period, value) in found.items():
        for second, (other_period, other_value) in found.items():
            if first != second and period == other_period:
                yield value, other_value


