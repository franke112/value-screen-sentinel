class Candidate:
    def __init__(self, ticker: str):
        self.ticker = ticker


def load_closes() -> dict[str, tuple[date, float]]:
    """The settled close of every candidate on 2026-08-21, from the price
    snapshot -- the price rule 8 strikes every yield on."""
    return {
        row["ticker"]: (date.fromisoformat(row["close_date"]), float(row["close"]))
        for row in csv.DictReader((FIXTURES / f"closes-{ASOF}.csv").open(encoding="utf-8"))
    }


def load() -> tuple[list[Candidate], dict[str, TickerFundamentals], FxTable]:
    """The frozen 2026-08-21 candidate set, exactly as phase 5 received it."""
    series: dict[str, list[SeriesPoint]] = {}
    for row in csv.DictReader((FIXTURES / f"series-{ASOF}.csv").open(encoding="utf-8")):
        series.setdefault(row["ticker"], []).append(
            SeriesPoint(row["ticker"], row["line"],
                        date.fromisoformat(row["period_end"]),
                        float(row["value"]), row["statement"],
                        # THE FIXTURE IS THE VENDOR PATH'S OWN OUTPUT, frozen
                        # from the 2026-08-21 fundamentals store. That path
                        # asks for `income_stmt` and `balance_sheet`, which
                        # ARE the annual statements, so twelve months is what
                        # was fetched -- the same declaration `snapshot.
                        # read_fundamentals` makes for the same rows, and not
                        # a fact about this test. E13 refuses to rank a flow
                        # line whose length is unrecorded, so leaving it off
                        # here would make the frozen answer unreachable for a
                        # reason that has nothing to do with the key.
                        12 if row["statement"] == "income" else None)
        )
    fields: dict[str, list[FieldValue]] = {}
    for row in csv.DictReader((FIXTURES / f"fields-{ASOF}.csv").open(encoding="utf-8")):
        fields.setdefault(row["ticker"], []).append(
            FieldValue(row["ticker"], row["name"], row["status"],
                       number=float(row["number"]) if row["number"] else None,
                       text=row["text"] or None)
        )
    records: dict[str, TickerFundamentals] = {}
    tickers: list[str] = []
    for row in csv.DictReader((FIXTURES / f"status-{ASOF}.csv").open(encoding="utf-8")):
        ticker = row["ticker"]
        tickers.append(ticker)
        records[ticker] = TickerFundamentals(
            ticker, row["status"], 1, 3,
            tuple(fields.get(ticker, ())), tuple(series.get(ticker, ())),
            error=row["error"] or None,
        )

    stored = json.loads((FIXTURES / f"fx-{ASOF}.json").read_text(encoding="utf-8"))
    table = FxTable()
    for pair, entry in stored["fx"].items():
        table.rates[pair] = Rate(pair, float(entry["rate"]),
                                 date.fromisoformat(entry["as_of"]), entry["source"])
    return [Candidate(t) for t in sorted(tickers)], records, table


