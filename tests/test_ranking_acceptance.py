def test_the_parts_bound_fires_on_no_name_and_the_vendors_refusals_were_artefacts(ranked):
    """L2, executed on the real 394 rather than on a hand-built record.

    Under rule 8 the bound judges totalCash - totalDebt against total assets,
    and not one of the 394 trips it. The four names it refused while it
    judged the VENDOR's enterpriseValue were artefacts of that field: their
    quote-summary net cash sits well inside their balance sheets, so each
    regains a yield from the parts -- LISP.SW at 4.3%, the figure the review
    computed by hand against the vendor's 27.6%.
    """
    refused = sorted(t for t, s in ranked.scored.items()
                     if s.earnings_yield is None and EV_IMPOSSIBLE_NOTE in s.note)
    assert refused == EV_REFUSED == []
    for ticker in VENDOR_EV_REFUSED:
        assert ranked.scored[ticker].earnings_yield is not None, ticker
        assert EV_IMPOSSIBLE_NOTE not in ranked.scored[ticker].note
    for ticker in ("CVNA", "LISP.SW", "SILEX.ST"):
        assert ranked.scored[ticker].quality_state == QUALITY_OK
        assert ticker in {r.ticker for r in ranked.main}
    # PLUS.L is Financial Services: it has no quality leg, so its yield puts
    # it in the earnings-yield-only section, where the vendor field had
    # kept it out.
    assert ranked.scored["PLUS.L"].quality_state == QUALITY_SECTOR
    assert "PLUS.L" in {r.ticker for r in ranked.yield_only}
    lisp = next(i for i, r in enumerate(ranked.main, start=1) if r.ticker == "LISP.SW")
    assert lisp == 183
    assert ranked.scored["LISP.SW"].earnings_yield == pytest.approx(0.0433, abs=5e-4)


